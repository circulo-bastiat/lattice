  var levels = Object.create(null);   // posKey -> current LEVEL (0..8); absent == 0, same as a
                                       // freshly-placed composter's default state (.decomp:44-45)
  function key(x, y, z) { return x + ',' + y + ',' + z; }

  /** The composter block state at a position, or 0 when the world has no composter there.
   *  D-591 (orchestrator, at merge): `composter` IS in this engine's registry (`NS.Reg.names`,
   *  900 blocks, with its `level` 0..8 states) -- the worker read the legacy `02_blocks.js`
   *  table, which is not the registry. So LEVEL lives in the REAL block state, as vanilla's
   *  `Properties.LEVEL_8` does; the position map below is only the fallback for a headless
   *  fixture with no World at all. */
  function stateAt(x, y, z) {
    var W = NS.World, R = NS.Reg, SR = NS.States;
    if (!W || !W.getBlock || !R || !R.PROP || R.PROP.level === undefined || !SR) return 0;
    var st = W.getBlock(x, y, z);
    if (!st || SR.name(st) !== 'composter') return 0;
    return st;
  }

  /** ComposterBlock's own LEVEL property read -- .decomp appendProperties, line 306-308. */
  Composter.level = function (x, y, z) {
    var st = stateAt(x, y, z);
    if (st) {
      var v = NS.States.propValue(st, NS.Reg.PROP.level);
      return v < 0 ? 0 : (+NS.Reg.valueNames[v] | 0);
    }
    var m = levels[key(x, y, z)];
    return m === undefined ? 0 : m;
  };

  /** Force a position's LEVEL (0..8). Not vanilla's own API -- vanilla only ever moves LEVEL
   *  through `addToComposter`/`emptyComposter`/`scheduledTick` below -- but every stateful-block
   *  check in this repo (see `hoppercheck.mjs`'s inventory pokes) needs a bare setter to reach a
   *  fixture state without replaying dozens of chance rolls, so this exposes one deliberately.
   *  On a real composter block it writes the block state (`World.setBlock`, which re-meshes). */
  Composter.setLevel = function (x, y, z, lvl) {
    lvl = Math.max(0, Math.min(Composter.LEVEL_MAX, lvl | 0));
    var st = stateAt(x, y, z);
    if (st) {
      var vid = NS.Reg.PVAL[String(lvl)];
      if (vid !== undefined) {
        var next = NS.States.withProp(st, NS.Reg.PROP.level, vid);
        if (next !== st) NS.World.setBlock(x, y, z, next);
      }
      return lvl;
    }
    if (lvl === 0) delete levels[key(x, y, z)]; else levels[key(x, y, z)] = lvl;
    return lvl;
  };

  /** ComposterBlock.addToComposter, .decomp:274-286. A LEVEL-0 composter's first item ALWAYS
   *  takes -- vanilla's own guard, `($$4 != 0 || !($$5 > 0.0F)) && !(rng() < $$5)`, collapses to
   *  a plain `rng() < chance` once level is nonzero, because `chance` is >0 for every CHANCE
   *  entry (this module's generator only ever emits chance>0 rows, so that half of the OR is
   *  always false) -- so the ONLY way to refuse an increase is level!=0 and a failed roll.
   *  Reaching LEVEL_READY (7) schedules the vanilla 20-tick pop to 8
   *  (`createAndScheduleBlockTick(pos, block, 20)`, .decomp:283-285) through the SAME scheduler
   *  `07b_behaviour.js`'s `B.schedule` already runs every other timed block through, and plays
   *  the fill/fill_success sound `playEffects` (.decomp:166-186) picks between on whether LEVEL
   *  actually moved.
   */
  function addToComposter(x, y, z, lvl, chance, rng) {
    var Snd = NS.Sound;
    if (lvl !== 0 && rng() >= chance) {
      if (Snd && Snd.play) Snd.play('block.composter.fill', { x: x + 0.5, y: y + 0.5, z: z + 0.5 });
      Composter.syncEvent(x, y, z, 0);
      return;
    }
    var next = lvl + 1;
    Composter.setLevel(x, y, z, next);
    if (next === Composter.LEVEL_READY) {
      var B = NS.Behave;
      if (B && B.schedule) B.schedule(x, y, z, 20, 0);
    }
    if (Snd && Snd.play) Snd.play('block.composter.fill_success', { x: x + 0.5, y: y + 0.5, z: z + 0.5 });
    Composter.syncEvent(x, y, z, 1);
  }

  /** `syncWorldEvent(1500, pos, filled ? 1 : 0)` (WorldEvents.COMPOSTER_USED): logged on `Composter.events` (a
   *  ring of the last 32, for the checks) and handed to the particle sink (`Particle.worldEvent` 1500). The
   *  sound is the caller's `Snd.play` above. */
  Composter.events = [];
  Composter.syncEvent = function (x, y, z, data) {
    var ev = Composter.events;
    ev.push({ id: 1500, x: x, y: y, z: z, data: data });
    if (ev.length > 32) ev.shift();
    if (NS.Particle && NS.Particle.worldEvent) NS.Particle.worldEvent(1500, x, y, z, data);
  };

  /** ComposterBlock.compost(state, world, stack, pos), .decomp:243-252 -- the exact public API
   *  FarmerWorkTask calls (.decomp names.tsv method_30232 `syncComposterEvent`,
   *  `performAdditionalWork`) rather than going through a player's right-click. Refuses (returns
   *  false, no side effect at all) any item outside `CHANCE` and any LEVEL >= LEVEL_READY (7) --
   *  vanilla's own gate is `level < 7`, NOT `level < LEVEL_MAX` (8): a level-7 composter refuses
   *  a NEW item exactly like a level-8 one does, it is just waiting on the scheduled tick rather
   *  than full. On acceptance the item IS ALWAYS CONSUMED -- vanilla decrements the stack
   *  unconditionally once `level<7 && compostable` (.decomp:245-249), win or lose the chance roll
   *  inside `addToComposter` -- so a "wasted" item with no visible level bump is correct
   *  behaviour, not a bug this should paper over. Returns true iff the item was consumed.
   */
  Composter.addItem = function (x, y, z, itemId, rng) {
    rng = rng || Math.random;
    var chance = Composter.CHANCE[itemId];
    if (chance === undefined) return false;                    // not compostable -- refused
    var lvl = Composter.level(x, y, z);
    if (lvl >= Composter.LEVEL_READY) return false;             // level 7 or 8 -- .decomp:244 `level < 7`
    addToComposter(x, y, z, lvl, chance, rng);
    return true;                                                 // consumed regardless of the roll
  };

  /** ComposterBlock.scheduledTick, .decomp:289-295 -- level 7 only. `state.cycle(LEVEL)` from 7
   *  over an IntProperty ranged 0..8 lands on 8 (the next value, no wrap -- `BlockState.cycle`
   *  only wraps past the LAST value in the property's range, and 8 IS the last), matching
   *  `onBlockAdded`'s own comment that 7 is a transient "about to pop" state. Returns false
   *  (claims nothing) for any position not tracked at exactly level 7, so a re-scheduled tick
   *  that arrives after something else already emptied or refilled the composter correctly
   *  no-ops instead of double-firing -- the same contract `07b_behaviour.js`'s other
   *  `scheduledTick` dispatch branches (`Rs.torchTick` etc.) already use.
   */
  Composter.scheduledTick = function (x, y, z) {
    if (Composter.level(x, y, z) !== Composter.LEVEL_READY) return false;
    Composter.setLevel(x, y, z, Composter.LEVEL_MAX);
    var Snd = NS.Sound;
    if (Snd && Snd.play) Snd.play('block.composter.ready', { x: x + 0.5, y: y + 0.5, z: z + 0.5 });
    return true;
  };

  /** ComposterBlock.emptyFullComposter, .decomp:254-266 -- level 8 only. Drops exactly one
   *  bone_meal item entity (`new ItemStack(Items.field_8324)`, .decomp:260 -- field_8324 is
   *  BONE_MEAL, confirmed against the same runtime reflection dump this file's CHANCE table
   *  used: `Registry.ITEM.getId(Items.field_8324)` prints `minecraft:bone_meal`) and resets
   *  LEVEL to 0 (`emptyComposter`, .decomp:268-272). Returns null for anything but a level-8
   *  composter -- `onUse`'s own gate (.decomp:235 `else if (level == 8)`) is the CALLER's job,
   *  exactly like `addItem`'s level<7 gate above.
   */
  Composter.extract = function (x, y, z) {
    if (Composter.level(x, y, z) !== Composter.LEVEL_MAX) return null;
    Composter.setLevel(x, y, z, 0);
    var EL = NS.EntityList;
    if (EL && EL.dropStack) {
      EL.dropStack(x + 0.15 + Math.random() * 0.7, y + 0.66, z + 0.15 + Math.random() * 0.7, 'bone_meal', 1);
    }
    var Snd = NS.Sound;
    if (Snd && Snd.play) Snd.play('block.composter.empty', { x: x + 0.5, y: y + 0.5, z: z + 0.5 });
    return { item: 'bone_meal', count: 1 };
  };

  /** ComposterBlock.onUse, .decomp:219-241 -- the minimal player right-click path, wired into
   *  `14l_use.js`'s `Use.blockUse` behind `isBlock(state, 'composter')`. That guard can never
   *  match today (this engine has no `composter` block registered -- see this file's own header
   *  and `Composter.OWED` below), so the hook is dead code until one exists, the exact shape
   *  `07b_behaviour.js`'s own scheduledTick dispatch already uses for not-yet-built pieces.
   *  `itemId` is the RESOLVED item NAME (`IT.nameOf(stack.i)`), not a stack -- the caller (the
   *  hook in `14l_use.js`) owns decrementing the real inventory stack and spawning nothing extra;
   *  this only says what happened. Mirrors `.decomp`'s three-way branch exactly:
   *    level<8 and item compostable -> insert attempt (a no-op click at level 7: .decomp:224 `<7`)
   *    level===8                    -> extract
   *    otherwise                    -> PASS (null)
   */
  Composter.onUse = function (x, y, z, itemId) {
    var lvl = Composter.level(x, y, z);
    if (lvl < Composter.LEVEL_MAX && Composter.CHANCE[itemId] !== undefined) {
      if (lvl < Composter.LEVEL_READY) return { consumed: Composter.addItem(x, y, z, itemId, Math.random) };
      return { consumed: false };                              // level 7: registers the click, does nothing
    } else if (lvl === Composter.LEVEL_MAX) {
      return { consumed: false, extracted: Composter.extract(x, y, z) };
    }
    return null;                                                 // PASS -- not a composter click vanilla handles
  };

