// 07zs_spawner.js — loop/spawner-s114 (PLAN G18c, D-395's own remainder): the MONSTER SPAWNER
// block entity's ENTITY ASSIGNMENT — the half `Spawn.tickSpawner` (07l_spawn.js) never got
// because nothing ever set `e.entity` to anything but the block entity's own fallback ('pig',
// 07c_blockentity.js:137-140). `Spawn.tickSpawner` was written and correct the whole time; the
// spawner cage worldgen placed was, and until this file, still is in the worker bundle, an
// EMPTY one (04n_feat_terrain.js's own "an empty cage that will never spawn anything").
//
// Runs on: MAIN THREAD ONLY (reads `NS.BlockEntities`, main-only per 07c's own header). AFTER
// 07c_blockentity.js (BE.create/BE.get) and 07l_spawn.js (nothing read at load time, sits with
// the mob that owns the spawner-block feature, same shelving 07zn_mooshroom.js's own header
// uses). Called from `04n_feat_terrain.js`'s dungeon feature and `04s_struct_mineshaft.js`'s
// cave-spider corridor — BOTH of which also run inside the WORKER bundle
// (`tools/loadsrc.mjs`'s own `WORKER_FILES`, ending at `05_mesher.js`), which this file is not
// part of, so every call here is guarded exactly the way `07zo_bee.js`'s own `Bee.stockNest`
// guards `NS.BlockEntities` (that file's own header names the same gap: "no chest, spawner or
// hopper generated by a tree/structure feature gets its content today either... until a generic
// worker-result -> W.installChunk -> BE.create channel exists for ALL of them"). #167 built that
// channel for spawners: the worker features record [x,y,z,id] in Gen.spawnerLog, genColumn returns
// it as `spawners`, gen:done carries it and World.installChunk calls Spawner.assign. And when the caller DOES share a
// JS context with `NS.BlockEntities` — `Jobs.mode==='inline'` (09_jobs.js, the no-Worker
// fallback) and every check/tool that loads the engine as one `Function` (`loadsrc.mjs`'s own
// `extra`, `spawnercheck.mjs` included) — a generated spawner now gets the RIGHT mob, not a
// bare cage.
(function (NS) {
  'use strict';

  var Spawner = NS.Spawner = {};

  /**
   * `Spawner.assign(x, y, z, entityId)` — ensure a `mob_spawner` block entity exists at this
   * cell and carries `entityId` as its `SpawnData` (`MobSpawnerLogic.setEntityId`,
   * `.decomp/net/minecraft/world/MobSpawnerLogic.java:42-44`). Every OTHER field
   * (`delay`/`minDelay`/`maxDelay`/`count`/`spawnRange`/`maxNearbyEntities`/
   * `requiredPlayerRange`) is left at `BlockEntities.js`'s own `make('mob_spawner', ...)`
   * defaults (20/200/800/4/4/6/16, D-208/D-395) — `setEntityId` is the ONLY field vanilla's own
   * `DungeonFeature`/`MineshaftGenerator` callers ever touch (below); a spawner that already
   * has NON-DEFAULT delay fields (e.g. one a `/data merge` or a future NBT loader set before
   * this runs) keeps them, matching `BE.onChanged`'s own "don't clobber a live entity, only
   * (re)create the missing one" rule (07c_blockentity.js:191-199).
   *
   * Returns false, doing nothing, when `NS.BlockEntities` is not in this JS context (the
   * worker-bundle gap named above) — the caller is expected to have already placed the bare
   * `spawner` BLOCK either way, exactly as it did before this file existed.
   */
  Spawner.assign = function (x, y, z, entityId) {
    var BE = NS.BlockEntities;
    if (!BE || !BE.ready || !BE.create || !BE.get) return false;
    var e = BE.get(x, y, z);
    if (!e || e.type !== 'mob_spawner') e = BE.create(x, y, z, 'mob_spawner');
    if (!e) return false;
    e.entity = entityId;
    return true;
  };

  // ── SpawnPotentials (#5722) — MobSpawnerLogic.readNbt/writeNbt/updateSpawns. `e.potentials` is
  // [{id, weight, data:{entity:{id,...NBT}}}]; `e.spawnData` is the current entry's data (its
  // entity NBT is applied to each mob spawned).
  var entId = function (d) { var i = d && d.entity && d.entity.id; return typeof i === 'string' ? i.replace(/^minecraft:/, '') : null; };
  /** WeightedList.getOrEmpty: weighted pick with `nextInt(total)`; null when empty / total 0. */
  Spawner.pickEntry = function (e, nextInt) {
    var p = e.potentials, tot = 0, i;
    if (!p || !p.length) return null;
    for (i = 0; i < p.length; i++) tot += Math.max(0, p[i].weight | 0);
    if (tot <= 0) return null;
    var r = nextInt(tot);
    for (i = 0; i < p.length; i++) { r -= Math.max(0, p[i].weight | 0); if (r < 0) return p[i]; }
    return null;
  };
  /** updateSpawns' tail: a non-empty list picks the next entry, else the single SpawnData stays. */
  Spawner.updateSpawnEntry = function (e, nextInt) {
    var en = Spawner.pickEntry(e, nextInt);
    if (!en) return false;
    e.entity = en.id; e.spawnData = en.data;
    return true;
  };
  /** Normalise a saved list ({data,weight}) into engine entries, dropping ones with no entity id. */
  Spawner.setPotentials = function (e, list) {
    e.potentials = [];
    for (var i = 0; i < (list || []).length; i++) {
      var id = entId(list[i] && list[i].data);
      if (id) e.potentials.push({ id: id, weight: list[i].weight === undefined ? 1 : list[i].weight | 0, data: list[i].data });
    }
  };
  /** The picked entry's entity NBT reaching the mob (Entity.readNbt subset: Health, Invulnerable, CustomName, Silent). */
  Spawner.applyEntityNbt = function (ent, data) {
    var n = data && data.entity;
    if (!ent || !n) return;
    if (typeof n.Health === 'number') ent.health = n.Health;
    if (n.Invulnerable) ent.invulnerable = true;
    if (n.CustomName !== undefined) ent.customName = n.CustomName;
    if (n.Silent) ent.silent = true;
  };

  // ── DUNGEON'S OWN RANDOM ENTITY — `DungeonFeature.MOB_SPAWNER_ENTITIES`/`getMobSpawnerEntity`
  // (`.decomp/net/minecraft/world/gen/feature/DungeonFeature.java:26-28,134-136`): a 4-element
  // array `{ SKELETON, ZOMBIE, ZOMBIE, SPIDER }` (`EntityType.field_6137/.field_6051/.field_6051/
  // .field_6079`, resolved against `EntityType.java:480,618,517`) drawn uniformly by
  // `Util.getRandom` — i.e. skeleton 1/4, zombie 2/4, spider 1/4. Vanilla rolls this AFTER up to
  // two loot-chest placements the same feature makes (this engine's own dungeon feature does
  // not build chest NBT at all, PLAN G17, named on this same file's own worldgen callers), so
  // the exact RNG-call-count parity with a seeded vanilla world is already lost upstream of
  // this line — matching vanilla's WEIGHTS here (not its call-site index) is what `spawnercheck
  // holds this table to.
  Spawner.DUNGEON_ENTITIES = ['skeleton', 'zombie', 'zombie', 'spider'];

  /** `nextInt` is any `function(bound)` returning `[0, bound)` — the dungeon feature's own `r`
   *  (`03b_noise.js`'s `LegacyRandom`/`Xoro`, both expose `.nextInt`) passed as
   *  `r.nextInt.bind(r)`, or a plain function in a check. */
  Spawner.pickDungeonEntity = function (nextInt) {
    return Spawner.DUNGEON_ENTITIES[nextInt(Spawner.DUNGEON_ENTITIES.length)];
  };

  // ── CAVE SPIDER -- `CaveSpiderEntity.tryAttack` (.decomp/net/minecraft/entity/mob/
  // CaveSpiderEntity.java:29-46, read whole): a landed melee hit ALSO applies Poison, duration
  // keyed off world difficulty at the moment of the hit -- 0 (no effect) on PEACEFUL/EASY,
  // 7*20 ticks on NORMAL (`Difficulty.field_5802`), 15*20 on HARD (`Difficulty.field_5807`),
  // amplifier 0. Same call shape as `Undead.onHuskHit` (07zk_undead.js) -- a hook `Cb.mobAttack`
  // (14j_combat.js) calls once a hit has actually landed, not a goal of its own.
  var CS = NS.CaveSpider = {};
  CS.POISON_TICKS = { normal: 7 * 20, hard: 15 * 20 };
  CS.onHit = function (e, target) {
    if (!e || e.type !== 'cave_spider' || !target) return;
    var Diff = NS.Diff, level = Diff && Diff.get ? Diff.get() : 'normal';
    var dur = CS.POISON_TICKS[level] || 0;
    if (!(dur > 0)) return;
    if (NS.Effects && NS.Effects.addStatusEffect) {
      NS.Effects.addStatusEffect(target, 'poison', dur, 0, false, true);
    }
  };

  // ── CLIENT SIDE — `MobSpawnerLogic.clientTick` (.decomp/net/minecraft/world/MobSpawnerLogic.java:
  // 49-63) and `MobSpawnerBlockEntityRenderer.render`. The block entity carries `spin`/`spinO`
  // (`field_9161`/`field_9159`); this engine's one tick serves client and server, so the delay
  // countdown stays with `Spawn.tickSpawner` (running just before this) and only the spin advance
  // and the two particles live here.
  Spawner.requiredRange = function (e) { return e.requiredPlayerRange !== undefined ? e.requiredPlayerRange : 16; };

  /** `rand` is any `function()` in [0,1) (a check's own, else Math.random); the position rolls
   *  are `world.random.nextDouble()` x3, one shared point for BOTH particles (java:54-59). */
  Spawner.clientTick = function (e, rand) {
    var P = NS.Player, Px = NS.Particle;
    if (!P) return false;
    var r = rand || Math.random;
    e.renderAge = (e.renderAge || 0) + 1;                     // the spawner's own tick -> the display mob's ageInTicks
    var reqR = Spawner.requiredRange(e);
    var dx = P.x - (e.x + 0.5), dy = P.y - (e.y + 0.5), dz = P.z - (e.z + 0.5);
    if (dx * dx + dy * dy + dz * dz > reqR * reqR) {          // isPlayerInRange: dist < range
      e.spinO = e.spin || 0;
      return false;
    }
    var x = e.x + r(), y = e.y + r(), z = e.z + r();
    if (Px && Px.spawn) {
      Px.spawn('smoke', x, y, z, 0, 0, 0, r);                 // ParticleTypes.SMOKE (field_11251)
      Px.spawn('flame', x, y, z, 0, 0, 0, r);                 // ParticleTypes.FLAME (field_11240)
    }
    e.spinO = e.spin || 0;
    var delay = e.delay > 0 ? e.delay : 0;
    e.spin = ((e.spin || 0) + Math.fround(1000 / (delay + 200))) % 360;
    return true;
  };

  /** `MobSpawnerBlockEntityRenderer.render`'s numbers for the mob at `e`: translate(.5,0,.5);
   *  f = 0.53125, divided by max(width,height) when that exceeds 1; translate(0,.4,0);
   *  rotateY(lerp(partial, spinO, spin)*10); translate(0,-.2,0); rotateX(-30); scale(f).
   *  Returns null for an entity type this engine cannot make (nothing to show). */
  Spawner.display = function (e, partial, dims) {
    var d = dims || (NS.Entities && NS.Entities.dimensions && NS.Entities.dimensions(NS.Entities.bare ? NS.Entities.bare(e.entity || 'pig') : 'pig'));
    var f = 0.53125;
    if (d) { var g = Math.max(d.width, d.height); if (g > 1) f /= g; }
    var o = e.spinO === undefined ? (e.spin || 0) : e.spinO;
    var spin = (o + ((e.spin || 0) - o) * partial) * 10;
    return { scale: f, lift: 0.2, spinDeg: spin, tiltDeg: -30 };
  };

  /** Every gap this stage names rather than silently leaves. `spawnercheck.mjs` holds this list
   *  closed the same way `Spawn.OWED`/`EL.owed()` are held closed elsewhere. */
  Spawner.OWED = [
    // struck #168/#5186: flame/smoke particles, the spinning mob and its -30 degree X tilt (ER.spawnerPoseOf).
    // struck #6338: idle animation state - ER.spawnerDisplays hands the spawner's tick count as the mob's age.
  ];
})(MCL);
