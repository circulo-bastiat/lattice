#!/usr/bin/env node
// extract-monsters.mjs — G18b-SG3. WHICH ENTITY TYPES ARE `instanceof net.minecraft.entity.mob.Monster`
// (the snow golem's ActiveTargetGoal filter), walked from the .decomp class hierarchy.
//
//   node tools/extract-monsters.mjs   -> tools/golden/monster-types-1.18.2.tsv
//
// EntityType.java's register calls give registry name -> `XxxEntity::new`; each class's `extends` /
// `implements` chain is followed through every .decomp source (interfaces too) to `Monster`.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DECOMP = join(ROOT, '.decomp');
const OUT = join(ROOT, 'tools', 'golden', 'monster-types-1.18.2.tsv');
if (!existsSync(DECOMP)) { console.error('extract-monsters: .decomp missing'); process.exit(1); }

const src = new Map();
(function walk(d) {
  for (const e of readdirSync(d, { withFileTypes: true })) {
    const p = join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.java')) src.set(e.name.slice(0, -5), p);
  }
})(join(DECOMP, 'net'));

const supers = (cls) => {
  const p = src.get(cls);
  if (!p) return [];
  const txt = readFileSync(p, 'utf8');
  const m = new RegExp('(?:class|interface)\\s+' + cls + '\\b([^{]*)\\{').exec(txt);
  if (!m) return [];
  return [...m[1].replace(/<[^<>]*(?:<[^<>]*>[^<>]*)*>/g, '').matchAll(/\b([A-Z]\w*)\b/g)].map((x) => x[1])
    .filter((n) => n !== cls && n !== 'extends' && n !== 'implements');
};
const memo = new Map();
const isMonster = (cls) => {
  if (cls === 'Monster') return true;
  if (memo.has(cls)) return memo.get(cls);
  memo.set(cls, false);
  const r = supers(cls).some(isMonster);
  memo.set(cls, r);
  return r;
};

const et = readFileSync(join(DECOMP, 'net/minecraft/entity/EntityType.java'), 'utf8');
const rows = [...et.matchAll(/"([a-z_]+)",\s*EntityType\.Builder\.(?:<\w+>)?create\((\w+)::new/g)];
if (rows.length < 100) { console.error('extract-monsters: only ' + rows.length + ' entity types parsed'); process.exit(1); }
const out = rows.filter((r) => isMonster(r[2])).map((r) => r[1] + '\t' + r[2]);
for (const must of ['zombie', 'hoglin', 'zoglin', 'phantom', 'ghast', 'slime', 'shulker', 'piglin', 'ender_dragon']) {
  if (!out.some((l) => l.startsWith(must + '\t'))) { console.error('extract-monsters: anchor ' + must + ' missing'); process.exit(1); }
}
if (out.some((l) => l.startsWith('cow\t'))) { console.error('extract-monsters: cow must not be a Monster'); process.exit(1); }
writeFileSync(OUT, '# monster-types-1.18.2.tsv — generated by tools/extract-monsters.mjs from .decomp\n# name\tclass\n' + out.join('\n') + '\n');
console.log('extract-monsters: ' + out.length + ' of ' + rows.length + ' entity types are Monsters -> ' + OUT);
