function dataKeysOf(src) {
  const at = src.indexOf('NS.DATA = {');
  if (at < 0) throw new Error('§DUP: cannot find the DATA literal — this check has gone blind');
  let i = at + 'NS.DATA = {'.length, depth = 1, keys = [], atKey = true;
  while (i < src.length && depth > 0) {
    const c = src[i];
    if (c === '/' && src[i + 1] === '/') { i = src.indexOf('\n', i); if (i < 0) break; continue; }
    if (c === '/' && src[i + 1] === '*') { i = src.indexOf('*/', i) + 2; continue; }
    if (c === '"' || c === "'" || c === '`') {
      const q = c; i++;
      while (i < src.length && src[i] !== q) i += (src[i] === '\\' ? 2 : 1);
      i++; continue;
    }
    if (c === '{' || c === '[' || c === '(') { depth++; i++; continue; }
    if (c === '}' || c === ']' || c === ')') { depth--; i++; atKey = depth === 1; continue; }
    if (c === ',' && depth === 1) { atKey = true; i++; continue; }
    if (depth === 1 && atKey && /[A-Za-z_$]/.test(c)) {
      const m = /^([A-Za-z_$][\w$]*)\s*:/.exec(src.slice(i));
      if (m) { keys.push(m[1]); i += m[0].length; atKey = false; continue; }
      atKey = false;
    }
    i++;
  }
  return keys;
}
