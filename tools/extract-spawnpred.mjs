#!/usr/bin/env node
// extract-spawnpred.mjs — #5124 (G18c-V1): the REAL spawn predicate of every mob, off the 1.18.2 jar.
//
//   node tools/extract-spawnpred.mjs [jar]   -> tools/golden/spawn-predicates-1.18.2.tsv
//
// In 1.18.2 a mob's natural-spawn predicate is NOT a virtual `checkMonsterSpawnRules` override: it is the
// method reference handed to `SpawnRestriction.register` (`ayr.<clinit>`), keyed by EntityType. So the
// truth for "which class does skeleton's predicate come from" is that static initialiser's invokedynamic
// targets, read with javap -v. EntityType field -> id comes from `axo.<clinit>` (ldc id; ...; putstatic).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { homedir } from 'node:os';
import { MCLITE_ROOT } from './loadsrc.mjs';

const jar = process.argv[2] || join(homedir(), '.mclite-referee/1.18.2/versions/1.18.2/server-1.18.2.jar');
if (!existsSync(jar)) { console.error('no 1.18.2 server jar at ' + jar); process.exit(2); }
const jp = (flags, cls) => execFileSync('javap', [...flags, '-p', '-cp', jar, cls], { encoding: 'utf8', maxBuffer: 1 << 28 });

const ayr = jp(['-v'], 'ayr');
const bs = {};
for (const m of ayr.slice(ayr.indexOf('BootstrapMethods:\n')).matchAll(
  /^  (\d+): #\d+ REF_invokeStatic java\/lang\/invoke\/LambdaMetafactory[^\n]*\n    Method arguments:\n[^\n]*\n\s+#\d+ REF_\w+ ([^\n]+?):\(/gm)) bs[m[1]] = m[2];
let cur = null; const reg = [];
for (const l of ayr.slice(ayr.indexOf('static {};')).split('\n')) {
  let m = l.match(/getstatic\s+#\d+\s+\/\/ Field axo\.(\w+):Laxo;/); if (m) cur = m[1];
  m = l.match(/invokedynamic #\d+,\s+0\s+\/\/ InvokeDynamic #(\d+):test/); if (m) reg.push([cur, bs[m[1]]]);
}
const id = {}; let s = null;
for (const l of jp([ '-c' ], 'axo').split('\n')) {
  let m = l.match(/ldc(?:_w)?\s+#\d+\s+\/\/ String (\w+)$/); if (m) s = m[1];
  m = l.match(/putstatic\s+#\d+\s+\/\/ Field (\w+):Laxo;/); if (m) id[m[1]] = s;
}
const names = readFileSync(join(MCLITE_ROOT, '.decomp/names.tsv'), 'utf8').split('\n').map((l) => l.split('\t'));
const yarn = (o, n) => { const r = names.find((x) => x[0] === 'method' && x[1] === o && x[2] === n && x[3].endsWith('Z') && x[3].includes('Laxo;')); return r ? r[5].split('/').pop() + '.' + r[6] : '?'; };
const rows = reg.map(([f, t]) => { const [c, n] = t.split('.'); return [id[f], t, yarn(c, n)]; }).sort((a, b) => a[0] < b[0] ? -1 : 1);
writeFileSync(join(MCLITE_ROOT, 'tools/golden/spawn-predicates-1.18.2.tsv'),
  '# spawn-predicates-1.18.2.tsv — generated by tools/extract-spawnpred.mjs (SpawnRestriction.<clinit>, javap -v)\n# mob\tobf_predicate\tyarn_predicate\n' +
  rows.map((r) => r.join('\t')).join('\n') + '\n');
console.log(rows.length + ' predicates');
