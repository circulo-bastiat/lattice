#!/usr/bin/env node
// extract-fall-entities.mjs — which entity types take fall damage, derived from the 1.18.2 class chain
// (.decomp/ Yarn sources), not typed.   node tools/extract-fall-entities.mjs -> tools/golden/fall-entities-1.18.2.tsv
// Columns: type, class(yarn), handle, handleOwner, compute, computeOwner
//   handle  = false  (first handleFallDamage in the chain is a bare `return false;`: no damage at all)
//           | entity (Entity's: non-living types, no damage path)
//           | living (LivingEntity's: damage = computeFallDamage)
//           | custom (a body with its own logic: player, horse, llama, creeper, falling_block)
//   compute = the first computeFallDamage override (living = LivingEntity's ceil(d-3-jump)*mult; fox -5, goat -10, horse ...)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const MC = join(ROOT, '.decomp');
const TYPES = join(ROOT, 'tools', 'golden', 'entity-types-1.18.2.tsv');
const OUT = join(ROOT, 'tools', 'golden', 'fall-entities-1.18.2.tsv');
if (!existsSync(join(MC, 'names.tsv'))) { console.log('SKIP - no .decomp; keep the committed TSV.'); process.exit(0); }

const yarn = new Map();   // obf class -> yarn path
for (const l of readFileSync(join(MC, 'names.tsv'), 'utf8').split('\n')) {
  const c = l.split('\t');
  if (c[0] === 'class' && c[1]) yarn.set(c[1], c[5]);
}
const src = new Map();
const load = (p) => { if (!src.has(p)) { const f = join(MC, p + '.java'); src.set(p, existsSync(f) ? readFileSync(f, 'utf8') : null); } return src.get(p); };
const simple = (p) => p.split('/').pop();
function parentOf(p) {
  const s = load(p); if (!s) return null;
  const m = s.match(new RegExp('class ' + simple(p) + '(?:<[^{]*?>)? extends (\\w+)'));
  if (!m) return null;
  const imp = s.match(new RegExp('import ([\\w.]+\\.' + m[1] + ');'));
  if (imp) return imp[1].replace(/\./g, '/');
  return p.slice(0, p.lastIndexOf('/') + 1) + m[1];   // same package
}
function body(s, name) {
  const i = s.search(new RegExp('\\b(public|protected) (boolean|int) ' + name + '\\('));
  if (i < 0) return null;
  const o = s.indexOf('{', i); let d = 0, j = o;
  for (; j < s.length; j++) { if (s[j] === '{') d++; else if (s[j] === '}' && --d === 0) break; }
  return s.slice(o + 1, j).trim();
}
const rows = [];
for (const l of readFileSync(TYPES, 'utf8').split('\n')) {
  if (!l || l[0] === '#') continue;
  const c = l.split('\t');
  const cls = c[0] === 'player' ? 'net/minecraft/entity/player/PlayerEntity' : yarn.get(c[6]);
  if (!cls) { console.error('no yarn name for ' + c[0] + ' ' + c[6]); process.exit(1); }
  let handle = null, hOwn = '', compute = null, cOwn = '';
  for (let p = cls; p && !(handle && compute); p = parentOf(p)) {
    const s = load(p); if (!s) break;
    if (!handle) {
      const b = body(s, 'handleFallDamage');
      if (b !== null) { handle = /^return false;$/.test(b) ? 'false' : simple(p) === 'LivingEntity' ? 'living' : simple(p) === 'Entity' ? 'entity' : 'custom'; hOwn = simple(p); }
    }
    if (!compute) {
      const b = body(s, 'computeFallDamage');
      if (b !== null) { compute = simple(p) === 'LivingEntity' ? 'living' : 'override'; cOwn = simple(p); }
    }
  }
  rows.push([c[0], simple(cls), handle || 'false', hOwn, compute || 'none', cOwn].join('\t'));
}
writeFileSync(OUT, '# fall-entities-1.18.2.tsv — generated by tools/extract-fall-entities.mjs from .decomp (handleFallDamage / computeFallDamage chain)\n# type\tclass\thandle\thandleOwner\tcompute\tcomputeOwner\n' + rows.join('\n') + '\n');
console.log(`fall-entities: ${rows.length} types, ${rows.filter((r) => r.split('\t')[2] === 'false').length} take no fall damage`);
