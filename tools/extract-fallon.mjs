#!/usr/bin/env node
// extract-fallon.mjs — vanilla's LANDING MULTIPLIERS (Block.fallOn), read from the 1.18.2 jar's BYTECODE.
//
//   node tools/extract-fallon.mjs [--if-missing]        -> tools/golden/fallon-1.18.2.tsv
//
// Descriptor-keyed (D-309), no names trusted: a "fallOn" override is a method with descriptor
// (L*;L*;L*;L*;F)V whose body calls a method with descriptor (FFL*;)Z (Entity.causeFallDamage).
// The multiplier is the float constant pushed immediately before that call's DamageSource.
// Rows: yarn class / multiplier / "block names" (from .decomp Blocks.java, for the check) / note.
// Classes that override fallOn WITHOUT calling causeFallDamage (e.g. powder snow) get multiplier "-".
// Blocks with no override use Block's own 1.0; everything else (cobweb, ladder, vine, scaffolding,
// sweet_berry_bush, water) has NO fallOn override: their zero is a different mechanism.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, existsSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireJar } from './paths.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'tools', 'golden', 'fallon-1.18.2.tsv');
if (process.argv.includes('--if-missing') && existsSync(OUT)) { console.log(' fallon-1.18.2.tsv present (--if-missing)'); process.exit(0); }
try { execFileSync('javap', ['-version'], { stdio: 'ignore' }); } catch { console.log('SKIP - no javap'); process.exit(0); }
const JAR = requireJar('1.18.2');
const work = mkdtempSync(join(tmpdir(), 'mclite-fallon-'));
try {
  execFileSync('unzip', ['-o', '-q', JAR, '-d', work]);
  const all = execFileSync('bash', ['-c', 'cd ' + JSON.stringify(work) + " && find . -name '*.class' | sed 's|^\\./||; s|\\.class$||' | tr '/' '.'"],
    { maxBuffer: 1 << 28 }).toString().trim().split('\n');
  const rows = [];
  for (let i = 0; i < all.length; i += 300) {
    const out = execFileSync('javap', ['-p', '-c', '-cp', work, ...all.slice(i, i + 300)], { maxBuffer: 1 << 29 }).toString();
    for (const cls of out.split(/\n(?=(?:public |final |abstract )*(?:class|interface) )/)) {
      const head = cls.match(/^(?:\w+ )*(?:class|interface) (\S+)/); if (!head) continue;
      const re = /^  [^\n]*\((?:L[^;]+;){4}F\);?\n[^\n]*\n?\s*descriptor: |^  [^\n(]*\(([^)]*)\)/gm;
      const parts = cls.split(/\n(?=  \S[^\n]*\(.*\)[^\n]*;\n    Code:)/);
      for (const p of parts) {
        const sig = p.match(/^\s*(?:\w+ )*void (\w+)\(((?:\S+, ){3}\S+, float)\)/);
        if (!sig || !/\n    Code:/.test(p)) continue;
        const calls = [...p.matchAll(/invoke\w+\s+#\d+\s+\/\/ Method [^\n]*:\(FF(?:L[^;]+;)\)Z/g)];
        const supers = /invoke\w+\s+#\d+\s+\/\/ Method [\w\/$]+\.\w+:\((?:L[^;]+;){4}F\)V/.test(p);
        let mult = '-';
        if (calls.length) {
          const before = p.slice(0, calls[0].index).split('\n').filter(l => /^\s+\d+: /.test(l));
          // the two instructions before the call's getstatic(DamageSource): [.., float-multiplier, getstatic]
          const m = before.slice(-3).map(l => l.trim());
          const fl = m.find(l => /fconst_|ldc\s+#\d+\s+\/\/ float/.test(l));
          const v = fl && (fl.match(/fconst_(\d)/) ? fl.match(/fconst_(\d)/)[1] : fl.match(/float ([\d.]+)f/)[1]);
          mult = String(parseFloat(v));
        }
        rows.push({ cls: head[1], mult, supers });
      }
    }
  }
  if (rows.length < 5) { console.log('x too few fallOn overrides found: ' + rows.length); process.exit(1); }
  // yarn names + block names
  const names = new Map();
  for (const l of readFileSync(join(ROOT, '.decomp', 'names.tsv'), 'utf8').split('\n')) {
    const c = l.split('\t'); if (c[0] === 'class') names.set(c[1], c[5].replace(/^.*\//, ''));
  }
  const blocks = readFileSync(join(ROOT, '.decomp', 'net/minecraft/block/Blocks.java'), 'utf8');
  const byClass = {};
  for (const m of blocks.matchAll(/"(\w+)",\s*new (\w+)\(/g)) (byClass[m[2]] ||= []).push(m[1]);
  const lines = ['# columns: yarn-class / multiplier passed to causeFallDamage ("-" = none) / blocks / calls-super', '# Generated by tools/extract-fallon.mjs from the 1.18.2 jar bytecode. Blocks WITHOUT an override use Block.fallOn = 1.0.'];
  const seen = new Set();
  const kept = rows.filter(r => { const y = names.get(r.cls) || r.cls; const k = y + r.mult; if (seen.has(k)) return false; seen.add(k);
    return y === 'Block' || y.endsWith('Block'); });
  for (const r of kept.sort((a, b) => a.cls.localeCompare(b.cls))) {
    const y = names.get(r.cls) || r.cls;
    lines.push([y, r.mult, y === 'Block' ? '(default)' : (byClass[y] || []).join(','), r.supers ? 'super' : ''].join('\t'));
  }
  writeFileSync(OUT, lines.join('\n') + '\n');
  console.log(' wrote ' + (lines.length - 2) + ' rows -> ' + OUT);
} finally { rmSync(work, { recursive: true, force: true }); }
