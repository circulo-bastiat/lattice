/** A directory is a golden world if it carries a manifest and at least one region file. */
function worldAt(d) {
  const reg = join(d, 'world', 'region');
  if (!existsSync(join(d, 'manifest.json')) || !existsSync(reg)) return null;
  if (!readdirSync(reg).some((f) => f.endsWith('.mca'))) return null;
  try {
    const m = JSON.parse(readFileSync(join(d, 'manifest.json'), 'utf8'));
    return { dir: d, seed: Number(m.seed), fullChunks: m.fullChunks | 0 };
  } catch { return null; }
}
