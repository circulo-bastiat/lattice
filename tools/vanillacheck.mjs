  // ⚠⚠ WHAT MAKES A CELL EVIDENCE, AND WHY A FLAT BLOCK FLOOR IS NOT THE WHOLE ANSWER.
  // §6 asks for 800 observed blocks before it will hold a world ratio to a band, and that floor
  // is the right instrument for a row near the band EDGE: 0.28x against 0.32x is a claim only a
  // large sample can make. It is the WRONG instrument for the errors this section exists to
  // find. `brown_mushroom` in a swamp is seven golden blocks against a hundred and thirty-eight
  // of MC-Lite's — nineteen times, and a flat floor of 400 throws the row away unread. Seven
  // against a hundred and thirty-eight is not a close call; it is the strongest signal in the
  // ledger. So a cell is EVIDENCE when either is true, and the two only ever ADD rows:
  //
  //   the block floor    at least PB_MIN_OBS golden blocks, exactly as §6 does it; or
  //   the interval       the two Poisson counts' log-ratio interval at Z sigma lies wholly
  //                      outside the band, which is a claim the counts themselves support.
  //
  // ⚠ THE INTERVAL IS NEVER ALLOWED TO EXCUSE A ROW THE BLOCK FLOOR ALREADY BOUNDS — that would
  // be loosening a bound to make something pass, and the ⚠ at the top of this file is about
  // exactly that. It is an OR, so every row §6's own floor would have held is still held.
  //
  // ⚠ AND A CELL VANILLA PLACES NONE OF IS PRINTED AND NOT BOUNDED. `deep_cold_ocean` has no
  // lush cave in the twelve chunks drawn and MC-Lite's twelve have one, so the row reads INF and
  // means "the sample drew a different cave", not "the pipeline is wrong". A zero denominator
  // carries no ratio; what it CAN carry is the never-generates test below, in the other
  // direction, where zero is the whole of the claim.
  const PB_MIN_CH = 8, PB_MIN_OBS = 400, PB_Z = 3.0;
  const PB_LO = 0.30, PB_HI = 2.40;
  /** The log-ratio interval of two Poisson counts. `m === 0` gets the rule of three. */
  function ratioCI(v, m) {
    if (!v) return null;
    if (!m) return [0, 3 / v];
    const se = Math.sqrt(1 / v + 1 / m), k = Math.exp(PB_Z * se), q = m / v;
    return [q / k, q * k];
  }
