//
//   node tools/vanillacheck.mjs [--chunks N] [--print]
//
// ⚠ WHY THIS EXISTS, AND WHAT IT IS NOT.
//
// Every worldgen check in this project compares MC-Lite against vanilla's JSON DATA — the
// splines in `noise_settings/overworld.json`, the six climate parameters in the biome files,
// the height providers in the ore features. `wgcheck`, `colcheck`, `climcheck`, `biomecheck`,
// `surfcheck` and `featcheck` are 200,000 assertions against files. Not one of them has ever
// compared MC-Lite against a world vanilla actually GENERATED, and the difference matters: the
// data says what the generator is CONFIGURED to do; only a generated world says what it DID.
// `docs/archive/NEXT.md` has carried "W8's ore counts have no vanilla parity data — sample ~100 chunks
// in the real game and paste the counts in" as an open gap for three sessions. This closes it.
//
// The golden vectors are real 1.18.2 Anvil region files, pregenerated by the real server jar
// (SHA-1 verified against the object hash in its Mojang URL) at seed 1337, with a post-shutdown
// NBT census proving every requested chunk reached `Status: full`. `_scratch/mclite/vg_pregen.js`
// on the machine that has a JVM is the driver; `pregen/manifest.json` is its receipt and this
// check refuses to run against a manifest that does not say what it expects.
//
// ── ⚠⚠ THE RULE THAT BOUNDS THIS FILE — Dan, 8 September 2026 ────────────────────────────────
//
//   "remember our worldgen isnt supposed to be always perfect parity and you should only
//    compare with earth mode off and on parts that can be directly and correctly compared
//    without trashing the :lite: part"
//
// The charter says worldgen may take THE MIDDLE PATH: vanilla's silhouette, a cheaper
// implementation. So a mismatch here is NOT automatically a bug, and a check that diffed block
// for block would be a machine for generating false alarms against a deliberate design. Every
// section below therefore states WHY its comparison is valid before it makes it, and the
// comparisons this file DELIBERATELY DOES NOT MAKE are named in section 8 with the decision
// that authorised each deviation. A dropped comparison that is not written down is indis-
// tinguishable from one nobody thought of.
//
// ⚠ CLIMATE EXPLICIT: VANILLA, BY NAME. D-182 made 'earth' the default at world creation, and
// this whole file is meaningless in earth mode — earth mode moves the biomes on purpose, and
// biome moves surface, feature and structure alike. `G.init` below says `climate: 'vanilla'`
// for the same reason `featcheck` does.
//
// ── WHAT IS COMPARED, AND WHY EACH ONE IS FAIR ──────────────────────────────────────────────
