const hash32 = (x, z) => { let h = (x * 374761393 + z * 668265263) | 0; h = (h ^ (h >>> 13)) * 1274126177 | 0; return (h ^ (h >>> 16)) >>> 0; };

/**
 * Census one golden world and draw its sample. ⚠ ONE FUNCTION FOR BOTH WORLDS (D-227): section
 * 10 reads its second world through this same code, so a difference between the two worlds can
 * never be a difference between two readers.
 */
function openWorld(dir, nchunks, tag) {
  const regdir = join(dir, 'world', 'region');
  const files = readdirSync(regdir).filter((f) => /^r\.-?\d+\.-?\d+\.mca$/.test(f)).sort();
  // A deterministic spread over the WHOLE box rather than a corner of it. Session 4's lesson, in
  // `docs/archive/NEXT.md`: "a test that runs at the origin tests the origin."
  let present = 0, partial = 0;
  const full = [];               // every Status:full chunk in the golden world
  const vanStarts = new Map();   // structure name -> [[cx,cz],...]
  for (const f of files) {
  for (const c of regionChunks(regdir, f)) {
    present++;
    const nb = chunkNBT(c);
    // ⚠ A CHUNK CAN BE PRESENT ON DISK AND NOT FINISHED. The ring around a forceloaded area is
    // saved at `structure_starts`, `biomes`, `liquid_carvers` or `features` — no decoration, no
    // ores, no surface. In this golden world 13,906 chunks are present and 7,570 are full, so a
    // reader that skipped this line would have compared MC-Lite's finished chunks against
    // 6,336 half-generated ones and charged every difference to MC-Lite.
    if (nb.Status !== 'full' && nb.Status !== 'minecraft:full') { partial++; continue; }
    // ⚠ THE DECODED CHUNK IS NOT KEPT. The first draft pushed `nb` here, which is fine at 6,626
    // golden chunks and dies at 11,626: the census held every decoded NBT tree at once and node
    // hit `Ineffective mark-compacts near heap limit` on a 3 GB VM. A referee that gets WORSE as
    // the answer key gets better is a referee with a shelf life. Only the coordinates and the
    // structure starts survive the census; §pass 2 below re-reads the NBT for the SAMPLE alone,
    // so the memory cost is the sample size and the pregen can grow without bound.
    full.push({ cx: c.cx, cz: c.cz, f });
    const st = (nb.structures || {}).starts || {};
    for (const k of Object.keys(st)) {
      const v = st[k];
      if (!v || !v.id || v.id === 'INVALID') continue;
      const nm = bare(k);
      if (!vanStarts.has(nm)) vanStarts.set(nm, []);
      vanStarts.get(nm).push([v.ChunkX, v.ChunkZ]);
    }
  }
}
  ok(full.length >= 1000, `${tag}only ${full.length} Status:full chunks in the golden world`);
  ok(partial > 0, tag + 'no partial chunks at all — the Status filter above cannot be doing anything');
  say(`   ${present} chunks present, ${full.length} of them Status:full (${partial} partial, correctly excluded)`);

  const order = full.slice().sort((a, b) => hash32(a.cx, a.cz) - hash32(b.cx, b.cz));
  const sample = order.slice(0, Math.min(nchunks, order.length));

// ── pass 2: decode the NBT for the SAMPLE only ──────────────────────────────────────────────
// One walk per region file that the sample actually touches, so the peak resident set is the
// sample rather than the whole golden world. See the note in the census above.
  {
    const want = new Map();                      // file -> Set of 'cx,cz'
    const rec = new Map();                       // 'cx,cz' -> the sample record
    for (const r of sample) {
      if (!want.has(r.f)) want.set(r.f, new Set());
      want.get(r.f).add(r.cx + ',' + r.cz);
      rec.set(r.cx + ',' + r.cz, r);
    }
    let got = 0;
    for (const [f, keys] of want) {
      for (const c of regionChunks(regdir, f)) {
        const k = c.cx + ',' + c.cz;
        if (!keys.has(k)) continue;
        rec.get(k).nb = chunkNBT(c);
        got++;
      }
    }
    ok(got === sample.length,
       `${tag}re-read ${got} of ${sample.length} sampled chunks out of the region files — the second pass lost some`);
    say(`   sample of ${sample.length} re-read from ${want.size} region files`);
  }
  return { dir, regdir, files, full, vanStarts, sample };
}
