  // to the ocean would be charging the wrong biome, and D-223 already names where a lush patch
  // lands as a licensed approximation. So a cell is bounded only where THE BIOME'S OWN FEATURE
  // LIST, in vanilla's biome JSON, places that block. Everything else is printed and left to §6's
  // world average, which is the instrument that can see it.
  //
  // ⚠ THE WALK IS THE PROLOGUE'S, NARROWED FROM "ANY FEATURE" TO "THIS BIOME'S FEATURES", and it
  // reuses the prologue's own `HARDCODED_FEATURE_BLOCKS` hand table rather than growing a second
  // one. The assertion below is what keeps the two honest: every block this walk finds must also
  // be in `FEATURE_BLOCKS`, the union the prologue computed over the whole registry, so the two
  // cannot drift apart without a failure saying so.
  const pbBiomeCache = new Map();
  function pbBiomeBlocks(biome) {
    if (pbBiomeCache.has(biome)) return pbBiomeCache.get(biome);
    const out = new Set(), seen = new Set();
    const WG = MCL.WG;
    const collect = (o) => {
      if (!o || typeof o !== 'object') return;
      if (Array.isArray(o)) { for (const v of o) collect(v); return; }
      if (typeof o.type === 'string' && o.config !== undefined) {
        const h = HARDCODED_FEATURE_BLOCKS[bare(o.type)];
        if (h) for (const b of h) out.add(b);
      }
      for (const k of Object.keys(o)) {
        const v = o[k];
        if (k === 'Name' && typeof v === 'string') out.add(bare(v));
        else if ((k === 'feature' || k === 'default') && typeof v === 'string') visit(bare(v));
        else collect(v);
      }
    };
    const visit = (name) => {
      if (seen.has(name)) return;
      seen.add(name);
      const j = WG.get('configured_feature', name);
      if (!j) {
        const pf = WG.get('placed_feature', name);
        if (pf && typeof pf.feature === 'string') return visit(bare(pf.feature));
        if (pf && pf.feature) return collect(pf.feature);
        return;
      }
      const h = HARDCODED_FEATURE_BLOCKS[bare(j.type)];
      if (h) for (const b of h) out.add(b);
      collect(j.config);
    };
    const bj = MCL.WG.get('biome', biome);
    for (const step of ((bj && bj.features) || [])) for (const f of (step || [])) visit(bare(f));
    pbBiomeCache.set(biome, out);
    return out;
  }

  /** Every (biome, block) cell out of an accumulator. Shared with this section's own breaks. */
  function pbRowsOf(A) {
    const out = [];
    for (const [bi, a] of A) {
      for (const k of new Set([...a.v.keys(), ...a.m.keys()])) {
        const v = a.v.get(k) || 0, m = a.m.get(k) || 0;
        out.push({ biome: bi, block: k, n: a.n, obs: v, mobs: m,
                   vch: a.vc.get(k) || 0, mch: a.mc.get(k) || 0,
                   van: v / a.n, mine: m / a.n, ratio: v ? m / v : Infinity, feature: featurePlaces(k) });
      }
    }
    return out.sort((x, y) => (x.biome < y.biome ? -1 : x.biome > y.biome ? 1 : y.obs - x.obs));
  }
