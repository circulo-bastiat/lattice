/** Unpack a 1.16+ paletted long array. ⚠ ENTRIES DO NOT STRADDLE A LONG since 1.16 — a reader
 *  written for the pre-1.16 packing produces a chunk that is subtly, plausibly wrong. */
function unpack(data, paletteLen, cells, minBits) {
  const out = new Uint16Array(cells);
  if (!data || paletteLen <= 1) return out;
  const bits = Math.max(minBits, 32 - Math.clz32(paletteLen - 1));
  const per = Math.floor(64 / bits);
  const mask = (1n << BigInt(bits)) - 1n, B = BigInt(bits);
  let i = 0;
  for (let w = 0; w < data.length && i < cells; w++) {
    let v = BigInt.asUintN(64, BigInt(data[w]));
    for (let k = 0; k < per && i < cells; k++) { out[i++] = Number(v & mask); v >>= B; }
  }
  return out;
}
