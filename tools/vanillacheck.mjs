// ── decode one golden chunk into the shapes every section below asks about ──
function vanChunk(rec, mut) {
  const nb = rec.nb;
  const top = new Int16Array(256).fill(-999), topName = new Array(256).fill(null);
  const ground = new Int16Array(256).fill(-999);
  const ores = new Map(), oresHi = new Map(), veg = new Map(), bio3 = new Map();
  let voidCells = 0; const voidBand = [0, 0, 0];
  for (const s of nb.sections.slice().sort((a, b) => b.Y - a.Y)) {
    const bs = s.block_states;
    if (!bs) continue;
    let pal = bs.palette.map((p) => bare(p.Name));
    if (mut && mut.topBlock) pal = pal.map((n) => (AIRRE.test(n) ? n : mut.topBlock));
    const cells = unpack(bs.data, pal.length, 4096, 4);
    const one = pal.length === 1;
    if (s.biomes) {
      let bp = s.biomes.palette.map(bare);
      if (mut && mut.biome) bp = bp.map(() => mut.biome);
      const bd = unpack(s.biomes.data, bp.length, 64, 1);
      for (let q = 0; q < 64; q++) bio3.set((s.Y << 6) + q, bp[bp.length === 1 ? 0 : bd[q]]);
    }
    for (let yy = 15; yy >= 0; yy--) {
      const wy = (s.Y << 4) + yy;
      for (let i = (yy << 8); i < (yy << 8) + 256; i++) {
        const nm = pal[one ? 0 : cells[i]];
        const ci = i & 255;
        if (VOIDRE.test(nm)) {
          if (top[ci] !== -999 && wy < top[ci] && wy >= DEEP_LO && wy <= DEEP_HI) { voidCells++; voidBand[bandOf(wy)]++; }
          if (AIRRE.test(nm)) continue;
        }
        if (ORE.test(nm)) { ores.set(nm, (ores.get(nm) || 0) + 1); if (wy >= ORE_HI_Y) oresHi.set(nm, (oresHi.get(nm) || 0) + 1); }
        if (VEG.test(nm)) veg.set(nm, (veg.get(nm) || 0) + 1);
        if (top[ci] === -999 && !VEG.test(nm) && !AIRRE.test(nm)) { top[ci] = wy; topName[ci] = nm; }
        if (ground[ci] === -999 && !VEG.test(nm) && !NOTGROUND.test(nm)) ground[ci] = wy;
      }
    }
  }
  // ⚠ §5's OWN BREAK, AND IT IS PER BAND ON PURPOSE (D-232). Scaling ONE y-band of the golden
  // void leaves the COLUMN total close enough that the aggregate ratio never leaves its band —
  // which is exactly the blindness the split exists to remove, so this is the mutation that
  // proves the split is read rather than printed.
  if (mut && mut.voidBandScale) {
    const vb = mut.voidBandScale.band | 0, by = mut.voidBandScale.by;
    const after = Math.round(voidBand[vb] * by);
    voidCells += after - voidBand[vb];
    voidBand[vb] = after;
  }
  if (mut && mut.dy) for (let i = 0; i < 256; i++) {
    if (top[i] !== -999) top[i] += mut.dy;
    if (ground[i] !== -999) ground[i] += mut.dy;
  }
  // §9's dispersion break: pull the golden terrain toward the waterline without moving its
  // middle, so the LEVEL comparisons stay put and only the SPREAD one can notice.
  if (mut && mut.gsquash) for (let i = 0; i < 256; i++) {
    if (ground[i] !== -999) ground[i] = (SEA + 1) + Math.round((ground[i] - (SEA + 1)) * mut.gsquash);
  }
  if (mut && mut.oreScale) for (const M of [ores, oresHi]) for (const k of [...M.keys()]) M.set(k, Math.round(M.get(k) * mut.oreScale));
  // ONE ore alone, so section 9 can invert the abundance ORDER rather than every magnitude at once
  if (mut && mut.oreScaleOne) for (const M of [ores, oresHi]) for (const k of [...M.keys()]) {
    if (k.replace(/^deepslate_/, '') === mut.oreScaleOne.ore) M.set(k, Math.round(M.get(k) * mut.oreScaleOne.by));
  }
  // section 6's own break: scale the GOLDEN vegetation and the decoration band must move (D-222)
  if (mut && mut.vegScale) for (const k of [...veg.keys()]) veg.set(k, Math.round(veg.get(k) * mut.vegScale));
  const surfBiome = new Array(256);
  for (let z = 0; z < 16; z++) for (let x = 0; x < 16; x++) {
    const ci = (z << 4) | x, wy = top[ci] === -999 ? SEA : top[ci];
    surfBiome[ci] = bio3.get(((wy >> 4) << 6) + (((wy >> 2) & 3) << 4) + ((((rec.cz << 4) + z) >> 2 & 3) << 2) + ((((rec.cx << 4) + x) >> 2 & 3))) || '?';
  }
  return { top, topName, ground, surfBiome, ores, oresHi, veg, voidCells, voidBand, bio3 };
}

// ── the same numbers out of MC-Lite ─────────────────────────────────────────
function mineChunk(cx, cz) {
  const col = G.genColumn(cx, cz);
  const top = new Int16Array(256).fill(-999), topName = new Array(256).fill(null);
  const ground = new Int16Array(256).fill(-999);
  const ores = new Map(), oresHi = new Map(), veg = new Map();
  let voidCells = 0; const voidBand = [0, 0, 0];
  for (let sy = CFG.SECTIONS_Y - 1; sy >= 0; sy--) {
    const sec = col.sec[sy];
    for (let yy = 15; yy >= 0; yy--) {
      const wy = MINY + sy * 16 + yy;
      for (let i = (yy << 8); i < (yy << 8) + 256; i++) {
        const id = S.get(sec, i);
        const ci = i & 255;
        if (!id) { if (top[ci] !== -999 && wy < top[ci] && wy >= DEEP_LO && wy <= DEEP_HI) { voidCells++; voidBand[bandOf(wy)]++; } continue; }
        const nm = SR.name(id);
        if (VOIDRE.test(nm) && top[ci] !== -999 && wy < top[ci] && wy >= DEEP_LO && wy <= DEEP_HI) { voidCells++; voidBand[bandOf(wy)]++; }
        if (ORE.test(nm)) { ores.set(nm, (ores.get(nm) || 0) + 1); if (wy >= ORE_HI_Y) oresHi.set(nm, (oresHi.get(nm) || 0) + 1); }
        if (VEG.test(nm)) veg.set(nm, (veg.get(nm) || 0) + 1);
        if (top[ci] === -999 && !VEG.test(nm)) { top[ci] = wy; topName[ci] = nm; }
        if (ground[ci] === -999 && !VEG.test(nm) && !NOTGROUND.test(nm)) ground[ci] = wy;
      }
    }
  }
  return { top, topName, ground, ores, oresHi, veg, voidCells, voidBand };
}

/** Walk the sample and pile up every statistic. `mut` perturbs the GOLDEN side only — which is
 *  what makes section 9 a real anti-vacuity test rather than a test of the mutation. */
const gscratch = new Float64Array(6);
function measure(sample, mut) {
  const R = {
    bSame: 0, bDiff: 0, bSameSurf: 0, bDiffSurf: 0, bMism: new Map(),
    resid: [], band: new Map(), chunks: 0,
    vTop: new Map(), mTop: new Map(),
    // D-230: the GROUND comparison, and the per-biome split of every disagreement into
    // "the surface rule answered differently" and "the column is not at the same height".
    gStat: new Map(), gResid: [], seaV: [], seaM: [],
    ruleDis: 0, heightDis: 0, colAgree: 0, colTot: 0, ruleRows: new Map(), splitTot: 0,
    vOre: new Map(), mOre: new Map(), vOreHi: new Map(), mOreHi: new Map(), vOreChunks: new Map(),
    vVeg: new Map(), mVeg: new Map(),
    vAir: 0, mAir: 0, airPair: [], vBand: [0, 0, 0], mBand: [0, 0, 0], voidChunk: [],
  };
  for (const rec of sample) {
    const V = vanChunk(rec, mut), M = mineChunk(rec.cx, rec.cz);
    R.chunks++;
    for (let i = 0; i < 256; i++) {
      if (V.top[i] === -999 || M.top[i] === -999) continue;
      const d = M.top[i] - V.top[i];
      R.resid.push(d);
      const b = V.top[i] < SEA ? 'below-sea' : V.top[i] < 100 ? 'sea..99' : V.top[i] < 140 ? '100..139' : '140+';
      if (!R.band.has(b)) R.band.set(b, []);
      R.band.get(b).push(d);
      const bi = V.surfBiome[i], vn = V.topName[i] || '?', mn = M.topName[i] || '?';
      if (!R.vTop.has(bi)) { R.vTop.set(bi, new Map()); R.mTop.set(bi, new Map()); }
      R.vTop.get(bi).set(vn, (R.vTop.get(bi).get(vn) || 0) + 1);
      R.mTop.get(bi).set(mn, (R.mTop.get(bi).get(mn) || 0) + 1);
      // ── D-230: split the disagreement, per biome, on whether the GROUND is at the same y ──
      if (!R.gStat.has(bi)) R.gStat.set(bi, { n: 0, col: 0, sameY: 0, rule: 0, height: 0, rows: new Map(),
                                              wet: 0, split: 0, same: 0, sameOK: 0 });
      const P = R.gStat.get(bi);
      P.n++; R.colTot++;
      const gOK = V.ground[i] !== -999 && M.ground[i] !== -999;
      const gd = gOK ? M.ground[i] - V.ground[i] : 99;
      if (gOK) R.gResid.push(gd);
      if (gd === 0) P.sameY++;
      if (vn === mn) { P.col++; R.colAgree++; }
      else if (gd === 0) {
        P.rule++; R.ruleDis++;
        P.rows.set(vn + ' -> ' + mn, (P.rows.get(vn + ' -> ' + mn) || 0) + 1);
        R.ruleRows.set(vn + ' -> ' + mn, (R.ruleRows.get(vn + ' -> ' + mn) || 0) + 1);
      } else { P.height++; R.heightDis++; }
      // ── D-236: WHICH SIDE OF THE WATERLINE, which is the half of a height residual that a
      // surface rule can actually see. A column that moves within dry land changes nothing; a
      // column that crosses the waterline changes the top block from grass to water. §3 charges
      // the first to the rule and the second to the named dispersion deviation.
      if (gOK) {
        const vw = V.ground[i] <= WET_MAX, mw = M.ground[i] <= WET_MAX;
        if (vw) P.wet++;
        if (vw !== mw) { P.split++; R.splitTot++; }
        else { P.same++; if (vn === mn) P.sameOK++; }
      }
      // ── and the sea-level band, conditioned on the INPUT rather than on either output ──
      // ⚠ CONDITIONING ON A HEIGHT BIASES A HEIGHT COMPARISON. Selecting columns by vanilla's
      // own surface y makes the residual regress toward the mean of that selection, and the
      // number that comes out is a property of the selection. The offset spline value is the
      // INPUT both engines share — biome parity is 99.99%, so the climate fields agree — and
      // the columns with no jaggedness and no terracing are the ones where MC-Lite's height is
      // exactly `offsetToY`, so this is a comparison of the two maps and nothing else.
      if (gOK) {
        COL.climateInto((rec.cx << 4) + (i & 15), (rec.cz << 4) + (i >> 4), gscratch);
        const off = COL.offsetAt(gscratch);
        if (Math.abs(off) <= 0.04 && COL.jaggednessAt(gscratch) <= 0.0001
            && COL.terraceStrength(gscratch[1]) <= 0) { R.seaV.push(V.ground[i]); R.seaM.push(M.ground[i]); }
      }
    }
    for (const [k, v] of V.ores) R.vOre.set(k, (R.vOre.get(k) || 0) + v);
    for (const [k, v] of M.ores) R.mOre.set(k, (R.mOre.get(k) || 0) + v);
    for (const [k, v] of V.oresHi) R.vOreHi.set(k, (R.vOreHi.get(k) || 0) + v);
    for (const [k, v] of M.oresHi) R.mOreHi.set(k, (R.mOreHi.get(k) || 0) + v);
    // ⚠ HOW MANY CHUNKS the ore appeared in at all, not how many blocks. It is the only honest
    // denominator for an ore vanilla makes fewer than one of per chunk — see section 4's emerald.
    for (const k of new Set([...V.ores.keys()].map((x) => x.replace(/^deepslate_/, '')))) R.vOreChunks.set(k, (R.vOreChunks.get(k) || 0) + 1);
    for (const [k, v] of V.veg) R.vVeg.set(k, (R.vVeg.get(k) || 0) + v);
    for (const [k, v] of M.veg) R.mVeg.set(k, (R.mVeg.get(k) || 0) + v);
    R.vAir += V.voidCells; R.mAir += M.voidCells;
    for (let b = 0; b < 3; b++) { R.vBand[b] += V.voidBand[b]; R.mBand[b] += M.voidBand[b]; }
    // ⚠ PAIRED, per chunk: each chunk is compared against ITS OWN vanilla twin, so a difference in
    // which biomes the sample drew cannot move the answer the way it moves an aggregate.
    if (V.voidCells >= 200) R.airPair.push(M.voidCells / V.voidCells);
    // ⚠ KEPT PER CHUNK, because §5's deep-share fence is a RATIO OF SUMS and a ratio of sums has
    // a sampling error that nothing in this file used to measure. See the bootstrap in §5.
    R.voidChunk.push([V.voidBand[0], V.voidCells, M.voidBand[0], M.voidCells]);
    for (const [k, v] of V.bio3) {
      const sy = k >> 6, q = k & 63;
      const wy = (sy << 4) + ((q >> 4) << 2), wz = (rec.cz << 4) + (((q >> 2) & 3) << 2), wx = (rec.cx << 4) + ((q & 3) << 2);
      const mine = bare(B.name(G.biomeAt3(wx, wy, wz)));
      const caveish = /caves|deep_dark/.test(mine) || /caves|deep_dark/.test(v);
      if (mine === v) { R.bSame++; if (!caveish) R.bSameSurf++; }
      else { R.bDiff++; if (!caveish) R.bDiffSurf++; R.bMism.set(v + ' -> ' + mine, (R.bMism.get(v + ' -> ' + mine) || 0) + 1); }
    }
  }
  return R;
}
