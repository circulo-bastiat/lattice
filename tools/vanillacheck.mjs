// ─────────────────────────────────────────────── the Anvil reader
// Anvil is a 4 KB header of 1,024 four-byte location entries — three bytes of sector offset and
// one of sector count — then, at each offset, an i32 length, a compression byte (2 = zlib) and
// an NBT payload. `tools/nbt.mjs` sniffs the compression itself, so the payload goes straight in.
function regionChunks(regdir, file) {
  const raw = readFileSync(join(regdir, file));
  const m = /^r\.(-?\d+)\.(-?\d+)\.mca$/.exec(file);
  const rx = +m[1], rz = +m[2];
  const out = [];
  for (let i = 0; i < 1024; i++) {
    const off = ((raw[i * 4] << 16) | (raw[i * 4 + 1] << 8) | raw[i * 4 + 2]) * 4096;
    if (!off) continue;
    const len = raw.readInt32BE(off);
    out.push({ cx: (rx << 5) + (i & 31), cz: (rz << 5) + (i >> 5), payload: raw.subarray(off + 5, off + 4 + len) });
  }
  return out;
}
