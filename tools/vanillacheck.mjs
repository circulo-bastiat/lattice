/**
 * §3's three column-weighted means out of any measure() result (D-230), so §9 can take the same
 * numbers off a mutated answer key. `minN` is the per-biome floor: §3 uses 400, §9's 18-chunk
 * sample uses 100 or it would have no eligible biome at all.
 */
function surfaceMeans(res, minN) {
  let wN = 0, ov = 0, col = 0, rule = 0, biomes = 0, split = 0;
  for (const [b, V] of res.vTop) {
    const n = [...V.values()].reduce((a, x) => a + x, 0);
    if (n < minN) continue;
    const M = res.mTop.get(b), P = res.gStat.get(b) || { col: 0, rule: 0 };
    let o = 0; for (const [k, v] of V) o += Math.min(v, M.get(k) || 0);
    wN += n; ov += o; col += P.col; rule += P.rule; split += (P.split || 0); biomes++;
  }
  return { n: wN, biomes, overlap: pct(ov, wN), column: pct(col, wN), rule: pct(rule, wN), split: pct(split, wN) };
}

