#!/usr/bin/env node
// extract-boat.mjs — G18a-1 (#209): the BOAT model layer, as boxes, out of .decomp.
//
//   node tools/extract-boat.mjs   -> tools/golden/boat-model-1.18.2.tsv
//
// ⚠ WHY A SECOND TABLE. `extract-models.mjs` reads the 155 STATIC `ModelLayers` fields; the boat's
// layer is `EntityModelLayers.createBoat(type)` — a factory, one call per wood — so the bytecode
// walk never sees it and `models-1.18.2.tsv` has no `boat` row. The boxes are in
// `BoatEntityModel.getTexturedModelData` (.decomp), read here structurally: every `addChild(name,
// builder, transform)` in that method, its `.uv(u, v)` and each `.cuboid(x, y, z, w, h, d)`.
// Same column layout as models-1.18.2.tsv; `pack-models.mjs` appends these rows to the layer table.
// ⚠ `water_patch` is NOT emitted: it is `RenderLayer.getWaterMask()` (depth only, no colour), so it
// has no pixels to draw — `ER.OWED_BOAT` names it. 1.18.2 has no chest boat (1.19), so no such layer.
// ⚠ ALL SIX WOODS SHARE THIS ONE LAYER (`createBoat` differs only in the layer NAME); only the
// texture differs, which is `FAMILY.boat` in extract-mob-textures.mjs.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SRC = join(ROOT, '.decomp/net/minecraft/client/render/entity/model/BoatEntityModel.java');
const OUT = join(ROOT, 'tools', 'golden', 'boat-model-1.18.2.tsv');

export function parseBoat(text) {
  const num = (s) => Function('"use strict"; return (' + s.replace(/\(float\)/g, '').replace(/(\d)F\b/g, '$1')
    .replace(/Math\.PI/g, '(Math.PI)') + ')')();
  const body = text.slice(text.indexOf('getTexturedModelData'));
  const rows = [];
  const re = /addChild\(\s*"(\w+)",\s*(ModelPartBuilder\.create\(\)[^;]*?),\s*(ModelTransform\.(?:of|pivot)\([^;]*?\))\s*\)\s*;/gs;
  let m;
  while ((m = re.exec(body))) {
    const [, name, builder, tf] = m;
    if (name === 'water_patch') continue;
    const uv = /\.uv\(\s*(\d+),\s*(\d+)\)/.exec(builder);
    const t = /ModelTransform\.(of|pivot)\(([^;]*)\)$/.exec(tf);
    const a = t[2].split(/,(?![^(]*\))/).map((s) => num(s.trim()));
    const pose = t[1] === 'of' ? a : [a[0], a[1], a[2], 0, 0, 0];
    for (const c of builder.matchAll(/\.cuboid\(([^)]*)\)/g)) {
      const b = c[1].split(',').map((s) => num(s.trim()));
      rows.push(['boat', name, uv[1], uv[2], ...b.slice(0, 6), ...pose, 0, 128, 64]);
    }
  }
  return rows;
}

if (process.argv[1] && process.argv[1].endsWith('extract-boat.mjs')) {
  if (!existsSync(SRC)) { console.error('extract-boat: ' + SRC + ' missing (run tools/fetch-vanilla-data / decomp)'); process.exit(1); }
  const rows = parseBoat(readFileSync(SRC, 'utf8'));
  const parts = new Set(rows.map((r) => r[1]));
  if (rows.length !== 9 || parts.size !== 7) { console.error('extract-boat: ' + rows.length + ' boxes / ' + parts.size + ' parts, expected 9 / 7'); process.exit(1); }
  const f = (v) => (typeof v === 'number' ? String(Math.fround(v)) : v);
  writeFileSync(OUT, '# layer\tpart\ttu\ttv\tx\ty\tz\tw\th\td\tpx\tpy\tpz\trx\try\trz\tmirror\tsheetW\tsheetH\n' +
    '# Generated by tools/extract-boat.mjs from BoatEntityModel.java (.decomp). water_patch omitted (depth-only mask).\n' +
    rows.map((r) => r.map(f).join('\t')).join('\n') + '\n');
  console.log('extract-boat: ' + rows.length + ' boxes, ' + parts.size + ' parts -> ' + OUT);
}
