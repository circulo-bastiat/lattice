// #6254: lockstep engineRow fills held/armour from e.equip (Eq.getEquipped); serverRow reads HandItems/ArmorItems. Swapping the helmet must fail on 'armour'.
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEngine } from '../loadsrc.mjs';
import { serverRow, engineRow, compareTraces } from './lockstep/trace.mjs';
const ASSETS = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'assets');
let bad = 0, n = 0; const ok = (c, m) => { n++; if (!c) { bad++; console.log('FAIL ' + m); } };
const M = loadEngine({ extra: ['02f_tags.js', '02g_items.js', '14f_inventory.js', '07_world.js', '07h_entities.js', '09b_sky.js', '14b_physics.js', '07y_equip.js', '07i_entitylist.js', '07l_spawn.js', '14i_hand.js', '14j_combat.js', '14d_survival.js'] });
const meta = JSON.parse(readFileSync(join(ASSETS, 'items.meta.json'), 'utf8'));
M.Items.init({ items: readFileSync(join(ASSETS, 'items.bin')).toString('base64'), itemsBytes: meta.rawBytes });
M.DATA = Object.assign({}, M.DATA, { entities: JSON.parse(readFileSync(join(ASSETS, 'entities.json'), 'utf8')) });
M.Entities.init(); M.EntityList.init(); M.Equip.init();
const Eq = M.Equip, IT = M.Items, gear = { Equip: Eq, Items: IT };
const z = { type: 'zombie', equip: [] };
Eq.setEquipped(z, IT.HEAD, Eq.stackOf('iron_helmet'));
Eq.setEquipped(z, IT.MAINHAND, Eq.stackOf('iron_sword'));
const none = {};
const snbt = (helmet) => ({ HandItems: [{ id: 'minecraft:iron_sword', Count: 1 }, {}], ArmorItems: [{}, {}, {}, { id: 'minecraft:' + helmet, Count: 1 }] });
const S = [serverRow(0, snbt('iron_helmet'))];
const E = [engineRow(0, z, { gear })];
ok(E[0].held === 'minecraft:iron_sword', 'held = mainhand id');
ok(JSON.stringify(E[0].armour) === '[null,null,null,"minecraft:iron_helmet"]', 'armour = [feet,legs,chest,head]');
ok(compareTraces(S, E, { fields: ['held', 'armour'] }) === null, 'matching gear equal');
let caught = 0;
const d = compareTraces([serverRow(0, snbt('diamond_helmet'))], E, { fields: ['held', 'armour'] });
if (d && d.tick === 0 && d.field === 'armour') caught++; else ok(false, 'helmet swap not caught on armour');
Eq.setEquipped(z, IT.MAINHAND, Eq.stackOf('iron_axe'));
const d2 = compareTraces(S, [engineRow(0, z, { gear })], { fields: ['held', 'armour'] });
if (d2 && d2.field === 'held') caught++; else ok(false, 'held swap not caught');
console.log(`${n} assertions, ${bad} failures, ${caught} breaks caught`);
if (bad) process.exit(1);
